r"""variant_prefix.py - the symbol prefix of one version's lift, for several versions of a title in one exe
(src/kernel/xbox_variant.h; maintainer rule 2026-11-01, every port).

    py -3 -I tools/variant_prefix.py <gen dir> <prefix>      -> <gen dir>/recomp_prefix.h

Writes one `#define NAME <prefix>NAME` for every symbol the lift defines or calls by name - every sub_XXXXXXXX
(with _gen / _enter forms) found in the generated sources, xbe_entry_point and the dispatch functions - and for
the four functions the port's manual file defines for its version (recomp_lookup_manual, recomp_icall_fail_log,
recomp_icall_not_code_log, recomp_unimpl). The port compiles that version's generated C and its manual file with
`-include <gen dir>/recomp_prefix.h` (cmake/XboxVariants.cmake): the generated C stays byte-identical, and within
the version every name resolves to its own copy. Outside (the runtime, the port's main.c) the unprefixed
recomp_lookup / recomp_lookup_manual are the forwarders of XBOX_VARIANT_FORWARDERS().

The prefix must be a valid C identifier start ("us_", "pal_a_"). A manual override's own sub_X names are covered
as long as the lift knows them (an override of a lifted function always is: the lift declares sub_X and sub_X_gen).
"""
import os
import re
import sys

# Every global the lift defines besides sub_ (recomp_dispatch.c, the partitions' xbe_entry_point) and the four the
# manual file defines. Burnout 3's first three-disc link found recomp_call_all missing here: a new global in the
# generator must be added to this list.
FIXED = ("recomp_lookup", "recomp_dispatch_init", "recomp_dispatch_flat_bytes", "recomp_get_count",
         "recomp_call_all", "xbe_entry_point", "recomp_lookup_manual", "recomp_icall_fail_log",
         "recomp_icall_not_code_log", "recomp_unimpl")
SUB_RE = re.compile(r"\bsub_[0-9A-Fa-f]{8}(?:_gen|_enter)?\b")
PREFIX_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def names(gen):
    found = set()
    for fn in sorted(os.listdir(gen)):
        if fn == "recomp_prefix.h" or not fn.endswith((".c", ".h")):
            continue
        with open(os.path.join(gen, fn), encoding="utf-8", errors="replace") as f:
            found.update(SUB_RE.findall(f.read()))
    return sorted(found)


def write(gen, prefix):
    if not PREFIX_RE.match(prefix):
        raise SystemExit(f"variant_prefix: '{prefix}' is not a C identifier prefix")
    subs = names(gen)
    if not subs:
        raise SystemExit(f"variant_prefix: no sub_ names in {gen} - not a lift?")
    lines = ["/* recomp_prefix.h - generated by tools/variant_prefix.py; the symbols of this version's lift get the",
             f" * prefix '{prefix}' so several versions link into one exe (src/kernel/xbox_variant.h). Forced into",
             " * every generated file and the manual file of this version with -include; never edit by hand. */",
             "#ifndef RECOMP_PREFIX_H", "#define RECOMP_PREFIX_H",
             f"#define RECOMP_VARIANT_PREFIX \"{prefix}\""]
    lines += [f"#define {n} {prefix}{n}" for n in FIXED]
    lines += [f"#define {n} {prefix}{n}" for n in subs]
    lines += ["#endif", ""]
    out = os.path.join(gen, "recomp_prefix.h")
    text = "\n".join(lines)
    old = None
    if os.path.exists(out):
        with open(out, encoding="utf-8") as f:
            old = f.read()
    if old != text:                       # unchanged: keep the timestamp, no rebuild of the version
        with open(out, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    return out, len(subs), old != text


def main(argv):
    if len(argv) != 2:
        print(__doc__)
        return 2
    out, n, changed = write(argv[0], argv[1])
    print(f"variant_prefix: {out}: {n} sub_ names + {len(FIXED)} fixed, prefix {argv[1]}"
          f"{'' if changed else ' (unchanged)'}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
