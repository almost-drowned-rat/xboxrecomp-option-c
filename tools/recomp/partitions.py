"""Stable partitions of the generated C (B1 item 2: incremental, partitioned codegen).

The old split cut the function list into chunks of N functions in address order. One function more or
less moved every later chunk boundary, so a single added seed or a newly hand-written override rewrote
(and recompiled) almost every chunk. Here a partition is an address range that stays where it is:

  * the ranges live in a per-game file (the game repo passes --partitions <file>; the toolkit only
    provides the mechanism). Each partition has a start address and a fixed index; the index is the
    file name (recomp_NNNN.c), the start the lowest address it owns.
  * a function belongs to the partition with the greatest start <= its entry address. That holds for
    every entry the function list has, aliases included (T2 pointer/imm aliases, switch-arm aliases,
    tail_jump_alias): an alias goes by its own entry address, so host and alias may land in different
    partitions, deterministically.
  * the first run (no file, or --repartition) balances the ranges by weight (the size of the generated
    C, a proxy for compile time) into ceil(functions / N) partitions. Later runs keep them; only a
    partition that grows beyond twice the target weight is split - at its weighted middle, the lower
    half keeps the index, the upper half takes the next free index - so no other file moves.

Pure functions; tools/recomp/translator.py does the I/O.
"""
import bisect
import json

VERSION = 1
SPLIT_FACTOR = 2.0       # a partition above SPLIT_FACTOR x target weight is split


def plan(entries, count):
    """Balanced partitions for entries [(addr, weight)] sorted by addr: [(start, index)], index 0..n-1."""
    if not entries:
        return [(0, 0)]
    count = max(1, min(count, len(entries)))
    total = sum(w for _, w in entries)
    per = total / count
    parts, acc = [(0, 0)], 0.0          # partition 0 starts at 0: it owns everything below the next start
    for addr, w in entries:
        if acc >= per * len(parts) and len(parts) < count:
            parts.append((addr, len(parts)))
        acc += w
    return parts


def assign(entries, parts):
    """{index: [addr, ...]} for entries [(addr, weight)]; every partition present, even an empty one."""
    starts = [s for s, _ in parts]
    out = {i: [] for _, i in parts}
    for addr, _ in entries:
        out[parts[bisect.bisect_right(starts, addr) - 1][1]].append(addr)
    return out


def split_oversized(entries, parts, target):
    """Split every partition heavier than SPLIT_FACTOR x target until none is.

    Returns (parts, splits) with splits = [(index, new_index, at_addr)]. A partition with a single
    function cannot be split and stays as it is."""
    parts = sorted(parts)
    weight = dict(entries)
    splits = []
    while True:
        members = assign(entries, parts)
        heavy = [(sum(weight[a] for a in members[i]), i) for _, i in parts
                 if len(members[i]) > 1 and sum(weight[a] for a in members[i]) > SPLIT_FACTOR * target]
        if not heavy:
            return parts, splits
        _, index = max(heavy, key=lambda h: (h[0], -h[1]))
        addrs = members[index]
        half, acc, at = sum(weight[a] for a in addrs) / 2.0, 0, addrs[-1]
        for k, a in enumerate(addrs[:-1]):
            acc += weight[a]
            if acc >= half:
                at = addrs[k + 1]
                break
        new_index = max(i for _, i in parts) + 1
        parts = sorted(parts + [(at, new_index)])
        splits.append((index, new_index, at))


def load(path):
    """The partition file, or None when there is none yet."""
    try:
        with open(path, "r", encoding="utf-8") as f:
            text = f.read()
    except FileNotFoundError:
        return None
    return parse(text, path)


def load_parts(text):
    """Only the sorted [(start, index)] of a partition file's text."""
    return parse(text)["parts"]


def parse(text, path="<partition file>"):
    data = json.loads(text)
    if data.get("version") != VERSION:
        raise ValueError(f"{path}: partition file version {data.get('version')}, expected {VERSION}")
    parts = sorted((int(p["start"], 16), int(p["index"])) for p in data["partitions"])
    if not parts or parts[0][0] != 0:
        raise ValueError(f"{path}: the first partition must start at 0x00000000")
    if len({i for _, i in parts}) != len(parts):
        raise ValueError(f"{path}: duplicate partition index")
    return {"parts": parts, "target": float(data["target_weight"])}


def dumps(parts, target):
    """The file text: stable formatting, so an unchanged layout is an unchanged file."""
    rows = ",\n".join(f'  {{"start": "0x{s:08X}", "index": {i}}}' for s, i in sorted(parts))
    return (f'{{\n "version": {VERSION},\n'
            f' "comment": "generated by tools/recomp --partitions; regenerate with --repartition",\n'
            f' "target_weight": {int(round(target))},\n'
            f' "partitions": [\n{rows}\n ]\n}}\n')


def layout(entries, existing, count, repartition=False):
    """Partitions for this run: (parts, target, splits, created).

    entries: [(addr, weight)] sorted by addr. existing: load() result or None. count: the partition
    count for a new layout."""
    total = sum(w for _, w in entries)
    if existing is None or repartition:
        parts = plan(entries, count)
        target = total / max(1, len(parts))
        return parts, target, [], True
    parts, splits = split_oversized(entries, existing["parts"], existing["target"])
    return parts, existing["target"], splits, False
